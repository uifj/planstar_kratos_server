CREATE TABLE IF NOT EXISTS `review` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `review_id` BIGINT UNSIGNED NOT NULL COMMENT '评论ID',
  `user_id` BIGINT UNSIGNED NOT NULL COMMENT '用户ID',
  `activity_id` BIGINT UNSIGNED NOT NULL COMMENT '演出ID',
  `content` TEXT COMMENT '内容',
  `rating` TINYINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '星级',
  `images` JSON COMMENT '图片',
  `videos` JSON COMMENT '视频',
  `is_liked` TINYINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '已赞',
  `likes` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '赞数',
  `reply_count` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '回复数',
  `status` TINYINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '状态',
  `num_plus_related` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '相关数',
  `page_index` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '页码（DTO 复用）',
  `page_size` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '页大小（DTO 复用）',
  `total_num` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '总数（DTO 复用）',
  `data` JSON COMMENT '自嵌套列表',
  `activity` JSON COMMENT '演出快照',
  `user` JSON COMMENT '用户快照',
  `gmt_create` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `gmt_modified` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_review_review_id` (`review_id`),
  KEY `idx_review_activity_id` (`activity_id`),
  KEY `idx_review_user_id` (`user_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='评论 / 评价（原 reviews）' ROW_FORMAT=DYNAMIC;

