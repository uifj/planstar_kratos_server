SET NAMES utf8mb4;

CREATE DATABASE IF NOT EXISTS `planstar_catalog`
  DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------
-- 1. 创意主档
--    - idea_id 为业务主键，与自增主键 id 同步写入（种子显式指定同一值）。
--    - hot_score 由运营/定时任务维护：初始取种子值，后续按
--      (support_count + oppose_count) / (hours_since_create + 2)^0.6 刷新。
--    - idx_idea_feed 支撑叠卡流游标分页（publish_status,status,hot_score）。
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `planstar_catalog`.`project_idea` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `idea_id` BIGINT UNSIGNED NOT NULL COMMENT '创意ID（业务主键，与 id 同步）',
  `user_id` BIGINT UNSIGNED NOT NULL COMMENT '发起人用户ID',
  `title` VARCHAR(120) NOT NULL COMMENT '创意标题',
  `summary` VARCHAR(280) NOT NULL COMMENT '一句话简介',
  `cover` VARCHAR(1024) DEFAULT '' COMMENT '封面图 URL',
  `category_id` BIGINT UNSIGNED NOT NULL COMMENT '企划一级品类ID',
  `stage` TINYINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '阶段：1 创意 / 2 已发布企划改造建议',
  `description` MEDIUMTEXT COMMENT '详细描述',
  `support_count` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '支持人数',
  `oppose_count` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '不支持人数',
  `coin_intent_sum` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '意向档位求和（仅统计，不扣费）',
  `hot_score` DECIMAL(12,4) NOT NULL DEFAULT 0 COMMENT '热度分（定时刷新）',
  `publish_status` TINYINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '发布状态：0 草稿 / 1 已发布 / 2 审核中 / 3 驳回',
  `status` TINYINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '状态：1 正常 / 0 下线',
  `gmt_create` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `gmt_modified` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_project_idea_idea_id` (`idea_id`),
  KEY `idx_idea_feed` (`publish_status`,`status`,`hot_score`),
  KEY `idx_idea_user` (`user_id`,`gmt_create`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='企划创意主档' ROW_FORMAT=DYNAMIC;

-- ---------------------------------------------------------------------
-- 2. 创意表态
--    - uk_idea_user 保证一人一卡一票，重复提交由服务端按幂等处理。
--    - coin_tier 仅支持时有意义（0/5/10/20，仅表达意愿，不扣星币）。
--    - reason_code 不支持时必填，reason_text 为自定义补充（不对外展示原文）。
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `planstar_catalog`.`project_idea_vote` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `idea_id` BIGINT UNSIGNED NOT NULL COMMENT '创意ID（逻辑外键 project_idea.idea_id）',
  `user_id` BIGINT UNSIGNED NOT NULL COMMENT '投票用户ID',
  `vote_type` TINYINT UNSIGNED NOT NULL COMMENT '表态类型：1 支持 / 2 不支持',
  `coin_tier` SMALLINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '意愿档位：0/5/10/20（仅支持）',
  `reason_code` VARCHAR(32) DEFAULT '' COMMENT '不支持理由编码',
  `reason_text` VARCHAR(200) DEFAULT '' COMMENT '自定义理由（≤100 字，仅聚合统计）',
  `gmt_create` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `gmt_modified` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_idea_user` (`idea_id`,`user_id`),
  KEY `idx_vote_idea_type` (`idea_id`,`vote_type`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='企划创意表态' ROW_FORMAT=DYNAMIC;

